/**
 * UI strings.
 *
 * All window labels live here, not in the markup: a translation replaces one
 * dictionary and does not need a pass over all files. The Russian dictionary
 * is also the reference: the `Dict` type comes from it, so another locale
 * cannot miss a key or add an extra one. That is a build error.
 *
 * Substitution is simple, `{name}`: there is no need for ICU syntax.
 * `Intl.PluralRules` picks plural forms, because Russian needs more than one
 * form for counts.
 */

/** Values for `{name}` substitution. */
export type Params = Record<string, string | number>;

/** Plural categories, with the same names as in `Intl.PluralRules`. */
type Category = "zero" | "one" | "two" | "few" | "many" | "other";

/** Plural forms. `other` is required; it is also the fallback. */
type Plural = Partial<Record<Category, string>> & { other: string };

type Message = string | Plural;

